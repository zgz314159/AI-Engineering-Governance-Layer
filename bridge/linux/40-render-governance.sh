#!/usr/bin/env bash
# Linux compat entry for scripts/40-render-governance.ps1
# Same core logic: render the single canonical source (governance/policy.json)
# into the Spec Kit constitutions, the RuleSync rule projection, the RuleSync
# config, and the generated Konsist architecture test.
#
# Minimal fixes vs. the .ps1 stage:
#   * the generated Konsist test imports `KoArchitectureCreator.assertArchitecture`
#     (there is no top-level `...architecture.assertArchitecture` symbol);
#   * RuleSync output is checked with the same `generate --check` used upstream.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
FIXTURE="$ROOT/fixture"
POLICY="$ROOT/governance/policy.json"
RULESYNC_CLI="$ROOT/upstream/rulesync/dist/cli/index.js"

mkdir -p "$FIXTURE/.specify/memory" \
         "$FIXTURE/.rulesync/rules" \
         "$FIXTURE/src/test/kotlin/com/example/governed/architecture"

# --- policy -> constitution / architecture / security / rule / konsist test ---
python3 - "$POLICY" "$FIXTURE" <<'PY'
import json, sys, os
policy = json.load(open(sys.argv[1]))
fx = sys.argv[2]

def w(path, text):
    with open(path, "w") as f:
        f.write(text)

principles = "\n".join(f"- {p}" for p in policy["principles"])
quality = "\n".join(f"- {q}" for q in policy["qualityGates"])

constitution = f"""# Project Constitution

Project: {policy['projectName']}
Policy version: {policy['policyVersion']}

## Engineering Principles
{principles}

## Definition of Done
{quality}

## Governance Rule
AI agents MUST NOT declare work complete unless the deterministic `qualityGate` passes.
Architecture changes MUST be explicit; they MUST NOT be introduced silently during implementation.

> GENERATED from `governance/policy.json`. Do not edit directly.
"""
w(f"{fx}/.specify/memory/constitution.md", constitution)

arch_lines = []
for layer in policy["layers"]:
    deps = "nothing" if not layer["mayDependOn"] else ", ".join(layer["mayDependOn"])
    arch_lines.append(f"- **{layer['name']}** (`{layer['package']}`) may depend on: **{deps}**.")
arch_text = "\n".join(arch_lines)

architecture = f"""# Architecture Constitution

## Layer Boundaries
{arch_text}

## Blocking Violations
- A layer depending on a layer not listed above is a blocking violation.
- Domain is independent and MUST NOT depend on presentation or data.
- AI agents MUST NOT weaken these boundaries merely to make an implementation easier.

## Evolution Policy
To change a layer boundary, update `governance/policy.json`, regenerate governance outputs, and make the policy change visible in review.

> GENERATED from `governance/policy.json`. Do not edit directly.
"""
w(f"{fx}/.specify/memory/architecture_constitution.md", architecture)

security = """# Security Constitution

This fixture intentionally contains only baseline governance:
- no secrets in source control;
- dependencies are pinned for the governance proof;
- CI must fail closed on quality-gate violations.

> GENERATED from `governance/policy.json`. Do not edit directly.
"""
w(f"{fx}/.specify/memory/security_constitution.md", security)

memory_guidance = """# Persistent Work Memory (optional)

AEGL can use Beads (bd) as an OPTIONAL long-horizon work graph and persistent
memory backend. AEGL owns session continuity; Beads owns the work graph;
RuleSync owns agent rules. When persistent work memory is enabled:
- aegl memory status   - check backend availability
- aegl memory ready    - long-horizon ready work (from bd ready)
- aegl bd ...          - task lifecycle (create / dep / update --claim / close / show)
- aegl memory remember - durable project knowledge only; secrets are rejected
- aegl handoff         - session continuity
Never run bd setup: it writes AGENTS.md / CLAUDE.md and would collide with RuleSync.
"""

rule = f"""---
targets:
  - "*"
root: true
description: "Generated governance policy shared across AI coding agents."
---

# AI Engineering Governance

{constitution}

{architecture}

{memory_guidance}"""
w(f"{fx}/.rulesync/rules/00-governance.md", rule)

def var(name):
    return name[0].lower() + name[1:]

decls = []
calls = []
for layer in policy["layers"]:
    decls.append(f'            val {var(layer["name"])} = Layer("{layer["name"]}", "{layer["package"]}")')
for layer in policy["layers"]:
    v = var(layer["name"])
    if not layer["mayDependOn"]:
        calls.append(f"            {v}.dependsOnNothing()")
    else:
        dep_vars = ", ".join(var(d) for d in layer["mayDependOn"])
        calls.append(f"            {v}.dependsOn({dep_vars})")

kotlin = f"""package com.example.governed.architecture

import com.lemonappdev.konsist.api.Konsist
import com.lemonappdev.konsist.api.architecture.KoArchitectureCreator.assertArchitecture
import com.lemonappdev.konsist.api.architecture.Layer
import org.junit.jupiter.api.Test

/**
 * GENERATED from governance/policy.json.
 * Do not edit this file directly.
 */
class GeneratedArchitectureTest {{
    @Test
    fun `layer dependency policy must hold`() {{
        Konsist
            .scopeFromProduction()
            .assertArchitecture {{
{chr(10).join(decls)}

{chr(10).join(calls)}
            }}
    }}
}}
"""
w(f"{fx}/src/test/kotlin/com/example/governed/architecture/GeneratedArchitectureTest.kt", kotlin)

# Deterministic RuleSync config (mirrors the .ps1 stage).
rulesync_config = """{
  "$schema": "https://github.com/dyoshikawa/rulesync/releases/download/v25.0.0/config-schema.json",
  "targets": {
    "claudecode": { "rules": true },
    "codexcli": { "rules": true },
    "cursor": { "rules": true }
  },
  "outputRoots": ["."],
  "delete": true,
  "verbose": true,
  "silent": false
}
"""
w(f"{fx}/rulesync.jsonc", rulesync_config)
print("[OK] rendered policy -> constitution / architecture / security / rule / konsist test")
PY

# --- RuleSync projections + drift check ---
cd "$FIXTURE"
echo "[RuleSync] generating Claude / Codex / Cursor rule projections"
node "$RULESYNC_CLI" generate --targets claudecode --features rules
node "$RULESYNC_CLI" generate --targets codexcli --features rules
node "$RULESYNC_CLI" generate --targets cursor --features rules

echo "[RuleSync] verifying generated outputs are current"
node "$RULESYNC_CLI" generate --targets claudecode --features rules --check
node "$RULESYNC_CLI" generate --targets codexcli --features rules --check
node "$RULESYNC_CLI" generate --targets cursor --features rules --check

echo "[OK] policy -> Spec Kit / Architecture Guard / RuleSync / Konsist rendered."
echo "RENDER: PASS"
